using System.Diagnostics;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using UnderGlass.Minds;
using UnderGlass.Sim;
using UnderGlass.Sim.Lives;

/// <summary>Retained fixed-seed recordings of the sourced pilot in the normal town. All learning
/// and probabilities come from the engine; no postprocessing supplies missing events.</summary>
internal static class EveningTrial
{
    private static readonly JsonSerializerOptions Json = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        NumberHandling = JsonNumberHandling.AllowNamedFloatingPointLiterals,
        Converters = { new JsonStringEnumConverter() },
    };

    public static int Run(string output, string? layaUrl)
        => RunAsync(output, layaUrl).GetAwaiter().GetResult();

    private static async Task<int> RunAsync(string output, string? layaUrl)
    {
        string root = FindRoot();
        string sourcePath = Path.Combine(root, "sim", "history", "penny-pam-gus.json");
        string historyText = File.ReadAllText(sourcePath);
        HistoryPack history = HistoryPack.Read(historyText);
        string historyHash = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(historyText))).ToLowerInvariant();
        string viewer = Path.GetRelativePath(output, Path.Combine(root, "sim", "viewer")).Replace('\\', '/');
        Directory.CreateDirectory(output);
        Write("history.json", historyText);
        var rows = new List<object>();
        var counts = new List<RunCount>();

        foreach (long seed in new long[] { 7, 29, 101 })
            await Record($"authored-seed{seed}", "Authored", seed, null);
        if (layaUrl is not null)
        {
            using var mind = new LivesLayaMind(new LivesLayaOptions { BaseUrl = layaUrl });
            await Record("laya-seed7", "Laya", 7, mind);
        }

        var summary = new
        {
            format = "under-glass-lives-evening-trial", version = 1,
            simulationOutput = true, syntheticScenario = false, historyFile = "history.json", historySha256 = historyHash,
            method = "Normal town, current routines and body rules. Only Penny, Pam and Gus use the new evening consumer. "
                + "Authored: seeds 7, 29 and 101, 35 days each. Optional Laya: seed 7, 35 days, with the same inputs and exact recorded-answer replay. "
                + "All seeds are retained. No outcome quotas or forced offers; quiet paths are evidence too.",
            comparisons = "Embedded history comparisons hold the immediate scene, option inputs, other memory and random draw fixed. "
                + "They remove one own reading at a time and recompute recall, eligibility, reasons and authored probabilities only. "
                + "Authored seed 7 also exports care and whereabouts comparisons with an identical ordinary recording. "
                + "Neither arm calls Laya or simulates later lives.",
            observerProjection = "The ordinary town recording is complete. livesRouting decisions, skipped choices, perceptions "
                + "and memory changes are exported only for Penny, Pam and Gus. Filtering happens after the simulation and tape verification. "
                + "Additional ablation files contain comparison receipts and an identical ordinary-world SHA-256, not duplicate whole recordings.",
            scope = "Future evening agreements and their actual outcomes, with sourced history and optional typed Laya choices. "
                + "This experimental recording block is not the full Lives observer 0.2 contract; no private inspiration is generated by this trial.",
            runs = counts,
        };
        Write("summary.json", JsonSerializer.Serialize(summary, Json));
        Write("index.html", EveningTrialReport.Render(JsonSerializer.SerializeToElement(new { summary, history, runs = rows }, Json), viewer));
        Console.WriteLine($"Wrote {output}");
        Console.WriteLine($"{counts.Count} fixed recordings; {counts.Sum(c => c.Plans)} offers; {counts.Sum(c => c.Completed)} completed; "
            + $"{counts.Sum(c => c.MatchedComparisons)} matched history comparisons; {counts.Sum(c => c.ModelChoices)} Laya choices.");
        return 0;

        void Write(string file, string value)
        {
            using var stream = new FileStream(Path.Combine(output, file), FileMode.CreateNew, FileAccess.Write, FileShare.None);
            using var writer = new StreamWriter(stream, new UTF8Encoding(false));
            writer.Write(value);
        }

        async Task Record(string id, string backend, long seed, ILivesDecisionMind? mind)
        {
            Console.WriteLine($"Recording {id}: 35 days...");
            TownData town = TownData.Default();
            town.Feelings.Acts.With("company,invitations");
            var options = new ReplayOptions
            {
                Seed = seed, Days = 35, Town = town, Nights = true, History = history,
                Label = $"Penny, Pam and Gus · future evenings · {backend} · seed {seed} · current routine baseline",
                LivesRouting = new() { Enabled = true, CompareHistory = new[]
                    { "ppg-penny-burden", "ppg-pam-saloon-wary", "ppg-gus-pam-wary" } },
                LivesCompany = new() { Enabled = true },
                LivesEvenings = new() { Enabled = true, Participants = new[] { "Penny", "Pam", "Gus" } },
            };
            var clock = Stopwatch.StartNew();
            Dictionary<string, object?> recording = await Replay.RecordAsync(options, new AuthoredReflectionMind(), livesMind: mind);
            clock.Stop();
            if (!recording.TryGetValue("livesEvenings", out object? value) || value is not JsonElement evening)
                throw new InvalidDataException("The enabled evening run produced no livesEvenings recording.");
            JsonElement[] updates = Items(evening, "updates"), choices = Items(evening, "choices"), outcomes = Items(evening, "outcomes");
            JsonElement[] decisions = Items(evening, "decisions");
            bool? tapeVerified = null;
            if (mind is not null)
            {
                LivesDecisionRecord[] tape = decisions.Select(d => d.Deserialize<LivesDecisionRecord>(Json)
                    ?? throw new InvalidDataException("An evening model record is null.")).ToArray();
                Write(id + "-tape.json", JsonSerializer.Serialize(tape, Json));
                var replayMind = new RecordedLivesDecisionMind(tape);
                Dictionary<string, object?> replay = await Replay.RecordAsync(options, new AuthoredReflectionMind(), livesMind: replayMind);
                replayMind.RequireConsumed();
                tapeVerified = JsonSerializer.Serialize(recording, Json) == JsonSerializer.Serialize(replay, Json);
                ProjectPilotObserver(replay);
                Write(id + "-replayed.json", JsonSerializer.Serialize(replay, Json));
                if (tapeVerified != true)
                {
                    Write(id + ".json", JsonSerializer.Serialize(recording, Json));
                    throw new InvalidDataException("The evening decision tape did not reproduce the full recording. Both recordings were preserved.");
                }
            }
            JsonElement routing = (JsonElement)recording["livesRouting"]!;
            LivesMemoryChange[] memory = routing.GetProperty("memoryChanges").Deserialize<LivesMemoryChange[]>(Json)!;
            var learning = memory.Where(c => c.CauseId?.StartsWith("evening:", StringComparison.Ordinal) == true
                    || c.CauseId?.StartsWith("company:evening:", StringComparison.Ordinal) == true)
                .Select(c => new
                {
                    c.Holder, c.At, c.CauseId,
                    associations = c.AddedAssociations.Select(a => new { a.Object, a.Amount }),
                    expectations = c.After.Expectations.Where(e => e.Entries.Any(entry => entry.CauseId == c.CauseId))
                        .Select(e => new { e.Key, before = c.Before.Expectations.FirstOrDefault(b => b.Key == e.Key)?.Chance ?? 1,
                            after = e.Chance, success = e.Entries.Last(entry => entry.CauseId == c.CauseId).Success }),
                }).ToArray();
            JsonElement[] plans = updates.GroupBy(u => u.GetProperty("plan").GetProperty("id").GetString())
                .Select(g => g.Last().GetProperty("plan")).ToArray();
            var comparisonChoices = choices.Where(c => c.TryGetProperty("comparison", out JsonElement comparison)
                && comparison.ValueKind == JsonValueKind.Object).ToList();
            var ablations = new List<object>();
            if (id == "authored-seed7")
            {
                // This only changes observer input, never the live memory. Verify ordinary world
                // output is identical before joining extra held-choice receipts to the review.
                foreach (var arm in new[] { ("care", "ppg-penny-care"), ("whereabouts", "ppg-penny-pam-away-weekday") })
                {
                    var comparedOptions = options with { LivesRouting = options.LivesRouting with { CompareHistory = new[] { arm.Item2 } } };
                    Dictionary<string, object?> compared = await Replay.RecordAsync(comparedOptions, new AuthoredReflectionMind());
                    string worldHash = OrdinaryWorldHash(recording);
                    if (worldHash != OrdinaryWorldHash(compared))
                        throw new InvalidDataException("An observer-only history comparison changed the ordinary world recording.");
                    string comparisonFile = id + "-compare-" + arm.Item1 + ".json";
                    JsonElement comparedBlock = (JsonElement)compared["livesEvenings"]!;
                    JsonElement[] armChoices = Items(comparedBlock, "choices").Where(c => c.TryGetProperty("comparison", out var pair)
                        && pair.ValueKind == JsonValueKind.Object).ToArray();
                    Write(comparisonFile, JsonSerializer.Serialize(new { suite = "evenings", version = 1,
                        observerOnlyRepeatOf = id + ".json", removedReading = arm.Item2, ordinaryWorldIdentical = true,
                        ordinaryWorldSha256 = worldHash, historySha256 = historyHash, choices = armChoices }, Json));
                    comparisonChoices.AddRange(armChoices);
                    ablations.Add(new { file = comparisonFile, removedReading = arm.Item2, ordinaryWorldIdentical = true });
                }
            }
            JsonElement[] comparisons = comparisonChoices.Select(c => c.GetProperty("comparison")).ToArray();
            int matched = comparisons.Count(c => c.GetProperty("comparable").GetBoolean());
            int modelChoices = decisions.Count(d => d.GetProperty("answer").GetProperty("backend").GetString() == "laya");
            var count = new RunCount(id, backend, seed, 35, clock.Elapsed.TotalSeconds, plans.Length,
                plans.Count(p => p.GetProperty("stage").GetString() == "Completed"),
                plans.GroupBy(p => p.GetProperty("stage").GetString()!).ToDictionary(g => g.Key, g => g.Count()),
                matched, comparisons.Length - matched,
                comparisons.Count(c => c.TryGetProperty("probabilitiesChanged", out var b) && b.ValueKind == JsonValueKind.True),
                comparisons.Count(c => c.TryGetProperty("selectionChanged", out var b) && b.ValueKind == JsonValueKind.True),
                modelChoices, decisions.Count(d => d.GetProperty("answer").GetProperty("called").GetBoolean()),
                decisions.Length - modelChoices, decisions.Length, tapeVerified);
            counts.Add(count);
            const string method = "Full town with the sourced Penny/Pam/Gus history pack and current routine baseline. "
                + "No forced meetings, plan success, bedtime extensions or private inspiration. "
                + "Each comparison removes one reading belonging to the chooser; it does not simulate an alternate life.";
            recording["trial"] = new { suite = "evenings", id, backend, method, historySha256 = historyHash, tapeVerified };
            ProjectPilotObserver(recording);
            Write(id + ".json", JsonSerializer.Serialize(recording, Json));
            rows.Add(new { id, label = backend + " · current routines", backend, seed, method, file = id + ".json",
                count, updates, choices, comparisons = comparisonChoices, ablations, outcomes, learning, tapeVerified, decisions });
            Console.WriteLine($"  {count.Plans} offers, {count.Completed} shared evenings, {matched} matched choices, {modelChoices} Laya choices, {clock.Elapsed.TotalSeconds:0.00}s.");
        }
    }

    private static JsonElement[] Items(JsonElement root, string key) => root.TryGetProperty(key, out var value)
        && value.ValueKind == JsonValueKind.Array ? value.EnumerateArray().ToArray() : Array.Empty<JsonElement>();

    private static string OrdinaryWorldHash(Dictionary<string, object?> recording) => Convert.ToHexString(SHA256.HashData(
        JsonSerializer.SerializeToUtf8Bytes(recording.Where(pair => pair.Key is not ("livesRouting" or "livesCompany" or "livesEvenings" or "trial"))
            .ToDictionary(pair => pair.Key, pair => pair.Value), Json))).ToLowerInvariant();

    /// <summary>Export-only filtering: the full runtime and exact replay comparison have already
    /// finished. Preserve the ordinary town and every selected holder's routing receipt.</summary>
    private static void ProjectPilotObserver(Dictionary<string, object?> recording)
    {
        if (!recording.TryGetValue("livesRouting", out var source) || source is not JsonElement block) return;
        var projected = block.EnumerateObject().ToDictionary(p => p.Name, p => (object?)p.Value);
        foreach (string key in new[] { "decisions", "skipped", "memoryChanges", "perceptions" })
            projected[key] = Items(block, key).Where(row => IsPilot(key == "decisions"
                ? row.GetProperty("decision").GetProperty("opportunity").GetProperty("holder").GetString()
                : row.GetProperty("holder").GetString())).ToArray();
        projected["observerProjection"] = new
        {
            holders = new[] { "Penny", "Pam", "Gus" }, afterSimulation = true,
            omitted = "Other holders' routing decisions, skipped choices, memory changes and perceptions. The ordinary town remains complete.",
        };
        recording["livesRouting"] = JsonSerializer.SerializeToElement(projected, Json);
    }

    private static bool IsPilot(string? holder) => holder is "Penny" or "Pam" or "Gus";

    private sealed record RunCount(string Id, string Backend, long Seed, int Days, double Seconds, int Plans,
        int Completed, IReadOnlyDictionary<string, int> Endings, int MatchedComparisons, int NonComparable,
        int ChangedProbabilities, int ChangedSelection, int ModelChoices, int NetworkCalls,
        int FallbackEvaluations, int RecordedEvaluations, bool? TapeVerified);

    private static string FindRoot()
    {
        foreach (string start in new[] { Environment.CurrentDirectory, AppContext.BaseDirectory })
            for (DirectoryInfo? directory = new(start); directory is not null; directory = directory.Parent)
                if (File.Exists(Path.Combine(directory.FullName, "sim", "viewer", "ui.css"))) return directory.FullName;
        throw new InvalidOperationException("Run from the repository so the review can link its shared viewer styles.");
    }
}
